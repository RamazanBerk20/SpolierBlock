import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
const cat = JSON.parse(readFileSync(fileURLToPath(new URL('../../data/catalog.json', import.meta.url)), 'utf8'));
assert.equal(cat.version, 1);
const W = cat.works;
const types = new Set(['movie', 'tv', 'game', 'book', 'anime', 'manga', 'comic']);
const keys = 'id title type year aliases characters pop ambiguous'.split(' ').sort().join();
W.forEach((w, i) => {
  assert.equal(Object.keys(w).sort().join(), keys, `keys ${w.id}`);
  assert.match(w.id, /^Q\d+$/); assert.ok(w.title && typeof w.title === 'string');
  assert.ok(types.has(w.type), 'type ' + w.id);
  assert.ok(w.year === null || Number.isInteger(w.year));
  assert.ok(Array.isArray(w.aliases) && w.aliases.length <= 8 && w.aliases.every((a) => typeof a === 'string' && a.length >= 3 && a.toLowerCase() !== w.title.toLowerCase()));
  assert.ok(Array.isArray(w.characters) && w.characters.length <= 8 && (w.pop >= 40 || !w.characters.length));
  assert.ok(Number.isInteger(w.pop) && typeof w.ambiguous === 'boolean');
  if (i) assert.ok(W[i - 1].pop >= w.pop, 'sorted');
});
assert.ok(W.length >= 15000, 'count ' + W.length);
const find = (t, f = () => true) => W.find((w) => w.title === t && f(w));
const bb = find('Breaking Bad');
assert.ok(bb && bb.type === 'tv' && !bb.ambiguous && bb.characters.includes('Walter White'), 'Breaking Bad');
assert.ok(find('The Witcher 3: Wild Hunt', (w) => w.type === 'game'), 'Witcher 3');
assert.ok(find('Up', (w) => w.year === 2009 && w.ambiguous), 'Up');
assert.ok(find('It', (w) => w.ambiguous), 'It');
const er = find('Elden Ring'); assert.ok(er && !er.ambiguous, 'Elden Ring');
assert.ok(find('Attack on Titan'), 'Attack on Titan');
const al = (t) => (find(t)?.aliases ?? []).map((a) => a.toLowerCase());
assert.ok(al('Grand Theft Auto VI').some((a) => a === 'gta vi' || a === 'gta 6'), 'GTA VI alias');
assert.ok(al('Grand Theft Auto V').some((a) => a === 'gta v' || a === 'gta 5'), 'GTA V alias');
if (!al('The Last of Us Part II').some((a) => a.includes('tlou'))) console.warn('WARN: no TLOU alias for The Last of Us Part II');
console.log('OK', W.length, 'works');
